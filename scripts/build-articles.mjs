// Build step: convert content/articles/<slug>/article.md into src/data/articles.js
// Run: node scripts/build-articles.mjs
import { mkdir, readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import path from 'node:path';

const root = fileURLToPath(new URL('../', import.meta.url));
const manifest = JSON.parse(
  await readFile(path.join(root, 'content/articles.json'), 'utf8'),
);

const escapeHtml = (s) =>
  s
    .replace(/&/g, '&amp;')
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;')
    .replace(/"/g, '&quot;');

const inline = (s) => escapeHtml(s).replace(/\*\*(.+?)\*\*/g, '<strong>$1</strong>');

function mdToHtml(md, slug) {
  const lines = md.split('\n');
  const out = [];
  let para = [];
  let list = null; // 'ul' | 'ol'

  const flushPara = () => {
    if (para.length) {
      out.push(`<p>${para.map(inline).join('<br>')}</p>`);
      para = [];
    }
  };
  const flushList = () => {
    if (list) {
      out.push(`</${list}>`);
      list = null;
    }
  };

  for (const raw of lines) {
    const line = raw.trim();

    if (!line) {
      flushPara();
      flushList();
      continue;
    }
    if (line.startsWith('> 系列：')) continue; // strip internal status metadata
    if (line.startsWith('# ')) continue; // title comes from manifest

    let m;
    if ((m = line.match(/^!\[(.*?)\]\((images\/[^)]+)\)/))) {
      flushPara();
      flushList();
      out.push(
        `<figure><img src="articles/${slug}/${m[2]}" alt="${escapeHtml(m[1])}" loading="lazy" data-article-img></figure>`,
      );
      continue;
    }
    if ((m = line.match(/^###\s+(.*)/))) {
      flushPara();
      flushList();
      out.push(`<h3>${inline(m[1])}</h3>`);
      continue;
    }
    if ((m = line.match(/^##\s+(.*)/))) {
      flushPara();
      flushList();
      out.push(`<h2>${inline(m[1])}</h2>`);
      continue;
    }
    if (line.startsWith('> ')) {
      flushPara();
      flushList();
      out.push(`<blockquote>${inline(line.slice(2))}</blockquote>`);
      continue;
    }
    if (/^(-|\*)\s+/.test(line)) {
      flushPara();
      if (list !== 'ul') {
        flushList();
        out.push('<ul>');
        list = 'ul';
      }
      out.push(`<li>${inline(line.replace(/^(-|\*)\s+/, ''))}</li>`);
      continue;
    }
    if (/^\d+\.\s+/.test(line)) {
      flushPara();
      if (list !== 'ol') {
        flushList();
        out.push('<ol>');
        list = 'ol';
      }
      out.push(`<li>${inline(line.replace(/^\d+\.\s+/, ''))}</li>`);
      continue;
    }
    if (/^---+$/.test(line)) {
      flushPara();
      flushList();
      out.push('<hr>');
      continue;
    }
    flushList();
    para.push(line);
  }
  flushPara();
  flushList();
  return out.join('\n');
}

const articles = [];
for (const meta of manifest) {
  const md = await readFile(
    path.join(root, 'content/articles', meta.slug, 'article.md'),
    'utf8',
  );
  articles.push({ ...meta, html: mdToHtml(md, meta.slug) });
  delete articles[articles.length - 1].cover; // covers are typographic in v1
}

await mkdir(path.join(root, 'src/data'), { recursive: true });
await writeFile(
  path.join(root, 'src/data/articles.js'),
  `// Generated by node scripts/build-articles.mjs. Edit content/articles/* instead.\nexport const articles = ${JSON.stringify(articles)};\n`,
);
console.log(`Built ${articles.length} articles -> src/data/articles.js`);
